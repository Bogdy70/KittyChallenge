export const DEFAULT_MESSAGES = Object.fromEntries(
  MESSAGE_FIELDS.map((f) => [f.key, f.value]),
);
export const MESSAGE_BY_KEY = Object.fromEntries(
  MESSAGE_FIELDS.map((f) => [f.key, f]),
);

export function renderMessage(overrides, key, params = {}) {
  const template = overrides?.[key]?.trim()
    ? overrides[key]
    : DEFAULT_MESSAGES[key];
  if (typeof template !== "string") return "";
  const values = {
    guide: overrides?.["guide.name"]?.trim() || DEFAULT_MESSAGES["guide.name"],
    ...params,
  };
  return template.replace(/\{(\w+)\}/g, (token, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : token,
  );
}

export function validateMessages(overrides) {
  if (!overrides || typeof overrides !== "object" || Array.isArray(overrides))
    throw Object.assign(new Error("Lista de mesaje nu este validă."), {
      status: 400,
    });
  const result = {};
  for (const [key, value] of Object.entries(overrides)) {
    const field = Object.hasOwn(MESSAGE_BY_KEY, key)
      ? MESSAGE_BY_KEY[key]
      : undefined;
    if (!field || typeof value !== "string" || value.length > field.maxLength)
      throw Object.assign(
        new Error("Mesaj necunoscut sau prea lung: " + (field?.label || key)),
        { status: 400 },
      );
    for (const match of value.matchAll(/\{(\w+)\}/g))
      if (!field.variables.includes(match[1]) && match[1] !== "guide")
        throw Object.assign(
          new Error(
            "Variabilă necunoscută în „" +
              field.label +
              "”: {" +
              match[1] +
              "}",
          ),
          { status: 400 },
        );
    if (value.trim() && value !== field.value) result[key] = value;
  }
  if (new TextEncoder().encode(JSON.stringify(result)).length > 120000)
    throw Object.assign(
      new Error("Mesajele pot avea împreună maximum 120 KB."),
      { status: 400 },
    );
  return result;
}
